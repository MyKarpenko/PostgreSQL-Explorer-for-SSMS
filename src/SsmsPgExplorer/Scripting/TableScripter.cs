using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using Npgsql;
using NpgsqlTypes;
using SsmsPgExplorer.Connection;
using SsmsPgExplorer.Model;

namespace SsmsPgExplorer.Scripting
{
    internal enum ScriptKind { Create, Drop, DropAndCreate }

    /// <summary>
    /// Generates table DDL from the catalog. Every fragment comes from PostgreSQL's own deparsers
    /// (format_type, pg_get_expr, pg_get_constraintdef, pg_get_indexdef, pg_get_triggerdef, pg_get_partkeydef ...)
    /// so the script matches what the server has. Read-only: only SELECTs against pg_catalog.
    /// </summary>
    internal static class TableScripter
    {
        private sealed class TableInfo
        {
            public string Schema, Name, Kind, Persistence, Owner, PartKey, Parents, PartBound, Tablespace, RelOptions, Comment, AccessMethod;
            public bool IsPartition, RowSecurity, ForceRowSecurity;
        }

        public static async Task<string> ScriptAsync(ServerRegistration server, string database, long relOid, ScriptKind kind, ScriptingOptions o, CancellationToken ct)
        {
            using (var conn = await ConnectionFactory.OpenAsync(server, database, readOnly: true, ct).ConfigureAwait(false))
            {
                // pg_get_constraintdef / format_type / pg_get_expr omit schemas that are on search_path
                // (e.g. "REFERENCES customers(id)"). An empty-ish search_path makes every reference schema-qualified.
                // The connection is pooled and DISCARD ALL'd on return, so this doesn't leak.
                if (o.SchemaQualify)
                    using (var set = new NpgsqlCommand("SET search_path = pg_catalog", conn))
                        await set.ExecuteNonQueryAsync(ct).ConfigureAwait(false);

                var t = await TableAsync(conn, relOid, ct).ConfigureAwait(false)
                        ?? throw new InvalidOperationException($"Relation oid {relOid} not found (dropped?).");
                var q = o.SchemaQualify ? $"{Q(t.Schema)}.{Q(t.Name)}" : Q(t.Name);
                var sb = new StringBuilder();

                if (o.IncludeHeaders)
                {
                    sb.AppendLine($"-- Table: {t.Schema}.{t.Name}");
                    sb.AppendLine($"-- Server: {server.DisplayName}   Database: {database}");
                    sb.AppendLine($"-- Script date: {DateTime.Now:yyyy-MM-dd HH:mm:ss}   Generated by PostgreSQL Explorer for SSMS");
                    sb.AppendLine();
                }

                if (kind != ScriptKind.Create)
                {
                    sb.AppendLine($"DROP TABLE {(o.CheckExistence ? "IF EXISTS " : "")}{q};");
                    if (kind == ScriptKind.Drop) return sb.ToString();
                    sb.AppendLine();
                }

                await CreateTableAsync(conn, relOid, t, q, o, sb, ct).ConfigureAwait(false);
                return sb.ToString();
            }
        }

        private static async Task CreateTableAsync(NpgsqlConnection conn, long oid, TableInfo t, string q, ScriptingOptions o, StringBuilder sb, CancellationToken ct)
        {
            var exists = o.CheckExistence ? "IF NOT EXISTS " : "";
            var persistence = t.Persistence == "u" ? "UNLOGGED " : t.Persistence == "t" ? "TEMPORARY " : "";
            sb.Append($"CREATE {persistence}TABLE {exists}{q}");

            var lines = new List<string>();
            var constraints = await ConstraintsAsync(conn, oid, ct).ConfigureAwait(false);

            if (t.IsPartition)
            {
                // Partition: columns come from the parent.
                sb.Append($"\n    PARTITION OF {t.Parents}");
                var inline = InlineConstraints(constraints, o).ToList();
                if (inline.Count > 0) sb.Append(" (\n    ").Append(string.Join(",\n    ", inline)).Append("\n)");
                sb.Append($"\n    {t.PartBound}");
            }
            else
            {
                foreach (var col in await ColumnsAsync(conn, oid, ct).ConfigureAwait(false))
                {
                    if (!col.IsLocal) continue; // inherited (INHERITS) columns come from the parent
                    var line = new StringBuilder($"{Q(col.Name)} {col.Type}");
                    if (o.Collation && !string.IsNullOrEmpty(col.Collation)) line.Append(" COLLATE ").Append(col.Collation);
                    if (o.Identity && col.Identity == "a") line.Append(" GENERATED ALWAYS AS IDENTITY");
                    else if (o.Identity && col.Identity == "d") line.Append(" GENERATED BY DEFAULT AS IDENTITY");
                    else if (col.Generated == "s") line.Append($" GENERATED ALWAYS AS ({col.Default}) STORED");
                    else if (o.Defaults && !string.IsNullOrEmpty(col.Default)) line.Append(" DEFAULT ").Append(col.Default);
                    if (col.NotNull && !(o.Identity && !string.IsNullOrEmpty(col.Identity))) line.Append(" NOT NULL");
                    lines.Add(line.ToString());
                }
                lines.AddRange(InlineConstraints(constraints, o));
                sb.Append(" (\n    ").Append(string.Join(",\n    ", lines)).Append("\n)");
                if (!string.IsNullOrEmpty(t.Parents) && t.Kind != "p") sb.Append($"\nINHERITS ({t.Parents})");
            }

            if (t.Kind == "p") sb.Append($"\nPARTITION BY {t.PartKey}");
            if (o.StorageOptions && !string.IsNullOrEmpty(t.AccessMethod) && t.AccessMethod != "heap") sb.Append($"\nUSING {t.AccessMethod}");
            if (o.StorageOptions && !string.IsNullOrEmpty(t.RelOptions)) sb.Append($"\nWITH ({t.RelOptions.Trim('{', '}').Replace(",", ", ")})");
            if (o.Tablespace && !string.IsNullOrEmpty(t.Tablespace)) sb.Append($"\nTABLESPACE {Q(t.Tablespace)}");
            sb.AppendLine(";");

            if (o.ForeignKeys)
            {
                var fks = constraints.Where(c => c.Type == "f").ToList();
                if (fks.Count > 0) sb.AppendLine();
                foreach (var fk in fks)
                    sb.AppendLine($"ALTER TABLE {q}\n    ADD CONSTRAINT {Q(fk.Name)} {fk.Definition};");
            }

            if (o.Indexes)
            {
                var idx = await ListAsync(conn, @"
SELECT pg_get_indexdef(i.indexrelid) || ';', obj_description(i.indexrelid, 'pg_class'), quote_ident(n.nspname) || '.' || quote_ident(ic.relname)
FROM pg_index i
JOIN pg_class ic ON ic.oid = i.indexrelid
JOIN pg_namespace n ON n.oid = ic.relnamespace
WHERE i.indrelid = @oid
  AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid AND c.conrelid = i.indrelid AND c.contype IN ('p','u','x'))
  AND NOT EXISTS (SELECT 1 FROM pg_inherits h WHERE h.inhrelid = i.indexrelid)   -- partition children of a partitioned index
ORDER BY ic.relname", oid, ct, 3).ConfigureAwait(false);
                if (idx.Count > 0) sb.AppendLine();
                foreach (var r in idx)
                {
                    var def = r[0];
                    if (o.CheckExistence) def = System.Text.RegularExpressions.Regex.Replace(def, @"^CREATE (UNIQUE )?INDEX ", "CREATE $1INDEX IF NOT EXISTS ");
                    if (!o.SchemaQualify) def = def.Replace($" ON {Q(t.Schema)}.", " ON ").Replace($" ON ONLY {Q(t.Schema)}.", " ON ONLY ");
                    sb.AppendLine(def);
                    if (o.Comments && !string.IsNullOrEmpty(r[1])) sb.AppendLine($"COMMENT ON INDEX {r[2]} IS {Lit(r[1])};");
                }
            }

            if (o.Statistics)
            {
                try
                {
                    var stats = await ListAsync(conn, "SELECT pg_get_statisticsobjdef(oid) || ';' FROM pg_statistic_ext WHERE stxrelid = @oid ORDER BY stxname", oid, ct, 1).ConfigureAwait(false);
                    if (stats.Count > 0) sb.AppendLine();
                    foreach (var s in stats) sb.AppendLine(s[0]);
                }
                catch (PostgresException) { sb.AppendLine("-- extended statistics: pg_get_statisticsobjdef needs PostgreSQL 14+"); }
            }

            if (o.Triggers)
            {
                var trg = await ListAsync(conn, "SELECT pg_get_triggerdef(oid, true) || ';' FROM pg_trigger WHERE tgrelid = @oid AND NOT tgisinternal ORDER BY tgname", oid, ct, 1).ConfigureAwait(false);
                if (trg.Count > 0) sb.AppendLine();
                foreach (var r in trg) sb.AppendLine(r[0]);
            }

            if (o.RowLevelSecurity && (t.RowSecurity || t.ForceRowSecurity))
            {
                sb.AppendLine();
                if (t.RowSecurity) sb.AppendLine($"ALTER TABLE {q} ENABLE ROW LEVEL SECURITY;");
                if (t.ForceRowSecurity) sb.AppendLine($"ALTER TABLE {q} FORCE ROW LEVEL SECURITY;");
                var pol = await ListAsync(conn, @"
SELECT 'CREATE POLICY ' || quote_ident(p.polname) || ' ON ' || @qname
       || CASE WHEN p.polpermissive THEN '' ELSE ' AS RESTRICTIVE' END
       || ' FOR ' || CASE p.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END
       || ' TO ' || COALESCE((SELECT string_agg(CASE WHEN r = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(r)) END, ', ') FROM unnest(p.polroles) r), 'PUBLIC')
       || COALESCE(' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')', '')
       || COALESCE(' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', '') || ';'
FROM pg_policy p WHERE p.polrelid = @oid ORDER BY p.polname", oid, ct, 1, q).ConfigureAwait(false);
                foreach (var r in pol) sb.AppendLine(r[0]);
            }

            if (o.Comments)
            {
                var comments = new List<string>();
                if (!string.IsNullOrEmpty(t.Comment)) comments.Add($"COMMENT ON TABLE {q} IS {Lit(t.Comment)};");
                foreach (var col in await ColumnsAsync(conn, oid, ct).ConfigureAwait(false))
                    if (!string.IsNullOrEmpty(col.Comment)) comments.Add($"COMMENT ON COLUMN {q}.{Q(col.Name)} IS {Lit(col.Comment)};");
                foreach (var c in constraints.Where(c => !string.IsNullOrEmpty(c.Comment)))
                    comments.Add($"COMMENT ON CONSTRAINT {Q(c.Name)} ON {q} IS {Lit(c.Comment)};");
                if (comments.Count > 0) { sb.AppendLine(); foreach (var c in comments) sb.AppendLine(c); }
            }

            if (o.Owner && !string.IsNullOrEmpty(t.Owner)) { sb.AppendLine(); sb.AppendLine($"ALTER TABLE {q} OWNER TO {Q(t.Owner)};"); }

            if (o.Permissions)
            {
                var grants = await ListAsync(conn, @"
SELECT CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END,
       string_agg(a.privilege_type, ', ' ORDER BY a.privilege_type), bool_or(a.is_grantable)::text
FROM pg_class c, aclexplode(c.relacl) a
WHERE c.oid = @oid AND a.grantee <> c.relowner
GROUP BY a.grantee ORDER BY 1", oid, ct, 3).ConfigureAwait(false);
                if (grants.Count > 0) sb.AppendLine();
                foreach (var g in grants) sb.AppendLine($"GRANT {g[1]} ON TABLE {q} TO {g[0]}{(g[2] == "true" ? " WITH GRANT OPTION" : "")};");
            }

            if (o.Partitions && t.Kind == "p")
            {
                var parts = await ListAsync(conn, @"
SELECT c.oid::text FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
WHERE i.inhparent = @oid ORDER BY c.relname", oid, ct, 1).ConfigureAwait(false);
                foreach (var p in parts)
                {
                    var childOid = long.Parse(p[0]);
                    var child = await TableAsync(conn, childOid, ct).ConfigureAwait(false);
                    if (child == null) continue;
                    sb.AppendLine();
                    var cq = o.SchemaQualify ? $"{Q(child.Schema)}.{Q(child.Name)}" : Q(child.Name);
                    // Child indexes come from the partitioned parent's indexes, so script only the table here.
                    var childOptions = new ScriptingOptions { IncludeHeaders = false, SchemaQualify = o.SchemaQualify, CheckExistence = o.CheckExistence, Comments = o.Comments, Indexes = false,
                        PrimaryKeys = false, UniqueKeys = false, CheckConstraints = true, ForeignKeys = false, StorageOptions = o.StorageOptions, Tablespace = o.Tablespace,
                        Defaults = o.Defaults, Identity = o.Identity, Collation = o.Collation, Partitions = true, FollowSsms = false };
                    await CreateTableAsync(conn, childOid, child, cq, childOptions, sb, ct).ConfigureAwait(false);
                }
            }
        }

        private static IEnumerable<string> InlineConstraints(List<Constraint> constraints, ScriptingOptions o) =>
            constraints.Where(c => (c.Type == "p" && o.PrimaryKeys) || (c.Type == "u" && o.UniqueKeys) || ((c.Type == "c" || c.Type == "x") && o.CheckConstraints))
                       .Select(c => $"CONSTRAINT {Q(c.Name)} {c.Definition}");

        // ---------- catalog reads ----------

        private static async Task<TableInfo> TableAsync(NpgsqlConnection conn, long oid, CancellationToken ct)
        {
            var rows = await ListAsync(conn, @"
SELECT n.nspname, c.relname, c.relkind::text, c.relpersistence::text, pg_get_userbyid(c.relowner),
       CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END,
       (SELECT string_agg(quote_ident(pn.nspname) || '.' || quote_ident(pc.relname), ', ' ORDER BY i.inhseqno)
          FROM pg_inherits i JOIN pg_class pc ON pc.oid = i.inhparent JOIN pg_namespace pn ON pn.oid = pc.relnamespace
         WHERE i.inhrelid = c.oid),
       c.relispartition::text,
       CASE WHEN c.relispartition THEN pg_get_expr(c.relpartbound, c.oid) END,
       ts.spcname, array_to_string(c.reloptions, ','), obj_description(c.oid, 'pg_class'),
       c.relrowsecurity::text, c.relforcerowsecurity::text, am.amname
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_tablespace ts ON ts.oid = c.reltablespace
LEFT JOIN pg_am am ON am.oid = c.relam
WHERE c.oid = @oid", oid, ct, 15).ConfigureAwait(false);
            if (rows.Count == 0) return null;
            var r = rows[0];
            return new TableInfo
            {
                Schema = r[0], Name = r[1], Kind = r[2], Persistence = r[3], Owner = r[4], PartKey = r[5], Parents = r[6],
                IsPartition = r[7] == "true", PartBound = r[8], Tablespace = r[9], RelOptions = r[10], Comment = r[11],
                RowSecurity = r[12] == "true", ForceRowSecurity = r[13] == "true", AccessMethod = r[14],
            };
        }

        private sealed class Column
        {
            public string Name, Type, Default, Identity, Generated, Collation, Comment;
            public bool NotNull, IsLocal;
        }

        private static async Task<List<Column>> ColumnsAsync(NpgsqlConnection conn, long oid, CancellationToken ct)
        {
            var rows = await ListAsync(conn, @"
SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull::text,
       pg_get_expr(d.adbin, d.adrelid), a.attidentity::text, a.attgenerated::text,
       CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation
            THEN (SELECT quote_ident(cn.nspname) || '.' || quote_ident(co.collname) FROM pg_collation co JOIN pg_namespace cn ON cn.oid = co.collnamespace WHERE co.oid = a.attcollation) END,
       col_description(a.attrelid, a.attnum), a.attislocal::text
FROM pg_attribute a
JOIN pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = @oid AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum", oid, ct, 9).ConfigureAwait(false);
            return rows.Select(r => new Column
            {
                Name = r[0], Type = r[1], NotNull = r[2] == "true", Default = r[3], Identity = r[4], Generated = r[5],
                Collation = r[6], Comment = r[7], IsLocal = r[8] == "true",
            }).ToList();
        }

        private sealed class Constraint { public string Name, Type, Definition, Comment; }

        private static async Task<List<Constraint>> ConstraintsAsync(NpgsqlConnection conn, long oid, CancellationToken ct)
        {
            var rows = await ListAsync(conn, @"
SELECT conname, contype::text, pg_get_constraintdef(oid, true), obj_description(oid, 'pg_constraint')
FROM pg_constraint
WHERE conrelid = @oid AND contype IN ('p','u','c','f','x') AND conislocal
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, conname", oid, ct, 4).ConfigureAwait(false);
            return rows.Select(r => new Constraint { Name = r[0], Type = r[1], Definition = r[2], Comment = r[3] }).ToList();
        }

        private static async Task<List<string[]>> ListAsync(NpgsqlConnection conn, string sql, long oid, CancellationToken ct, int columns, string qname = null)
        {
            var list = new List<string[]>();
            using (var cmd = new NpgsqlCommand(sql, conn) { CommandTimeout = 60, AllResultTypesAreUnknown = true })
            {
                cmd.Parameters.AddWithValue("oid", NpgsqlDbType.Oid, (uint)oid);
                if (qname != null) cmd.Parameters.AddWithValue("qname", qname);
                using (var r = await cmd.ExecuteReaderAsync(ct).ConfigureAwait(false))
                    while (await r.ReadAsync(ct).ConfigureAwait(false))
                    {
                        var row = new string[columns];
                        for (var i = 0; i < columns; i++) row[i] = r.IsDBNull(i) ? null : r.GetString(i);
                        list.Add(row);
                    }
            }
            return list;
        }

        /// <summary>quote_ident equivalent: quote unless all lower-case [a-z0-9_] and not starting with a digit.</summary>
        internal static string Q(string ident)
        {
            if (string.IsNullOrEmpty(ident)) return "\"\"";
            var plain = (char.IsLower(ident[0]) || ident[0] == '_') && ident.All(ch => (ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9') || ch == '_' || ch == '$');
            return plain && !Reserved.Contains(ident) ? ident : "\"" + ident.Replace("\"", "\"\"") + "\"";
        }

        private static string Lit(string s) => "'" + s.Replace("'", "''") + "'";

        // Enough reserved words that a column named e.g. "user" or "order" gets quoted.
        private static readonly HashSet<string> Reserved = new HashSet<string>(StringComparer.Ordinal)
        {
            "all","analyse","analyze","and","any","array","as","asc","asymmetric","both","case","cast","check","collate","column","constraint","create",
            "current_catalog","current_date","current_role","current_time","current_timestamp","current_user","default","deferrable","desc","distinct",
            "do","else","end","except","false","fetch","for","foreign","from","grant","group","having","in","initially","intersect","into","lateral",
            "leading","limit","localtime","localtimestamp","not","null","offset","on","only","or","order","placing","primary","references","returning",
            "select","session_user","some","symmetric","system_user","table","then","to","trailing","true","union","unique","user","using","variadic",
            "when","where","window","with","authorization","binary","collation","concurrently","cross","current_schema","freeze","full","ilike","inner",
            "is","isnull","join","left","like","natural","notnull","outer","overlaps","right","similar","tablesample","verbose",
        };
    }
